import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright');
const origin = process.env.CORTEX_TEST_URL || 'http://127.0.0.1:5177';
const browser = await chromium.launch({ headless: true, executablePath: process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE });
const context = await browser.newContext({ viewport: { width: 1440, height: 960 } });
const page = await context.newPage();
const errors = [];
page.on('pageerror', error => errors.push(error.message));
const channels = Array.from({ length: 6000 }, (_, i) => ({ id: `classic-${i}`, name: `Channel ${i + 1}`, logo: null, country: 'JO', categories: ['news'], languages: ['ara'], is_nsfw: false }));
await context.route('https://iptv-org.github.io/api/channels.json', route => route.fulfill({ json: channels }));
await context.route('https://iptv-org.github.io/api/streams.json', route => route.fulfill({ json: channels.map(c => ({ channel: c.id, url: `${origin}/fixture/${c.id}.m3u8` })) }));
await context.route('**/fixture/*.m3u8', route => route.fulfill({ body: 'invalid manifest', contentType: 'application/vnd.apple.mpegurl' }));
await mkdir('docs/screenshots/classic', { recursive: true });
try {
  await page.goto(origin);
  await page.locator('canvas').waitFor();
  await page.getByText('Global IPTV Explorer', { exact: true }).waitFor({ state: 'hidden' });
  assert.equal(await page.getByText('Every channel.', { exact: true }).count(), 0);
  await page.screenshot({ path: 'docs/screenshots/classic/globe-desktop.png' });
  await page.getByRole('button', { name: 'Open navigation', exact: true }).click();
  await page.getByRole('button', { name: 'Search Channels Find any public stream' }).click();
  const dialog = page.getByRole('dialog');
  await dialog.waitFor();
  const input = dialog.getByRole('textbox');
  await input.fill('Channel 1009');
  await dialog.getByText('Channel 1009', { exact: true }).waitFor();
  const inputStyle = await input.evaluate(e => ({ padding: getComputedStyle(e.parentElement).paddingLeft, outline: getComputedStyle(e).outlineStyle }));
  assert.ok(parseFloat(inputStyle.padding) > 0);
  assert.equal(inputStyle.outline, 'none');
  const box = await dialog.locator('.classic-search-panel').boundingBox();
  const closeBox = await dialog.getByRole('button', { name: 'Close search', exact: true }).boundingBox();
  assert.ok(closeBox.x >= box.x && closeBox.x + closeBox.width <= box.x + box.width + 1);
  await page.screenshot({ path: 'docs/screenshots/classic/search-desktop.png' });
  await dialog.getByText('Channel 1009', { exact: true }).click();
  await page.locator('[data-classic-player]').waitFor();
  assert.equal(await page.locator('video').count(), 1);
  assert.ok(await page.locator('.classic-player-guide [data-channel-results] [role=button]').count() < 50);
  await page.getByRole('heading', { name: 'Signal unavailable' }).waitFor({ timeout: 60000 });
  await page.screenshot({ path: 'docs/screenshots/classic/player-desktop.png' });
  await page.keyboard.press('ArrowDown');
  await page.waitForFunction(() => document.querySelector('.classic-player-title h1')?.textContent !== 'Channel 1009');
  assert.equal(await page.locator('video').count(), 1);
  await page.setViewportSize({ width: 390, height: 844 });
  const theatre = await page.locator('.theatre').boundingBox();
  const guide = await page.locator('.classic-player-guide').boundingBox();
  assert.ok(guide.y >= theatre.y + theatre.height - 1 && guide.height > 120);
  await page.screenshot({ path: 'docs/screenshots/classic/player-mobile.png' });
  await page.getByRole('button', { name: 'Back to browse' }).click();
  await page.locator('nav').getByRole('button', { name: 'Search', exact: true }).click();
  await dialog.waitFor();
  await dialog.getByRole('textbox').fill('Channel 12');
  await dialog.getByText('Channel 12', { exact: true }).waitFor();
  await page.screenshot({ path: 'docs/screenshots/classic/search-mobile.png' });
  await dialog.getByRole('button', { name: 'Close search', exact: true }).click();
  await dialog.waitFor({ state: 'hidden' });
  assert.deepEqual(errors, []);
  console.log('PASS: original globe interface; desktop/mobile search, spacing, close button, virtualized guide, one video, remote switching, recovery UI.');
} catch (error) { console.error(await page.locator('body').innerText()); throw error; }
finally { await browser.close(); }
